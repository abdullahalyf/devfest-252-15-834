// Real-browser acceptance with unchanged organizer files. Optional Playwright runtime.
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const fixture = path.join(root, 'problem_statement/problem-pack/sample-pack');
const docs = path.join(fixture, 'documents');
const evidenceRoot = process.env.ACCEPTANCE_EVIDENCE_DIR ? path.resolve(process.env.ACCEPTANCE_EVIDENCE_DIR) : root;
const output = path.join(evidenceRoot, 'output');
const screenshots = path.join(evidenceRoot, 'screenshots');
await mkdir(output, { recursive: true });
await mkdir(screenshots, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [], unexpectedRequests = [], results = [];
const acceptanceUrl = process.env.ACCEPTANCE_URL || 'http://127.0.0.1:5173/';
const expectedOrigin = new URL(acceptanceUrl).origin;
page.on('pageerror', e => errors.push(e.message));
page.on('request', request => {
  const url = request.url();
  if (!['GET', 'HEAD'].includes(request.method()) || (!url.startsWith('blob:') && !url.startsWith('data:') && new URL(url).origin !== expectedOrigin)) {
    unexpectedRequests.push(`${request.method()} ${url}`);
  }
});
const idle = async () => { await page.waitForFunction(() => document.querySelector('#app')?.getAttribute('data-busy') === 'false'); };
const record = message => { results.push(message); console.log(`PASS ${message}`); };
const match = async (id, name) => {
  const select = page.locator(`#tp-match-${id}`);
  const value = await select.locator('option').evaluateAll((options, filename) => options.find(o => o.textContent.startsWith(filename + ' — '))?.value, name);
  assert.ok(value, `Option for ${name}`);
  await select.selectOption(value);
};
try {
  await page.goto(acceptanceUrl);
  await idle();
  assert.equal(await page.locator('#tp-generate').isDisabled(), true);
  await page.locator('#tp-json-input').setInputFiles(path.join(fixture, 'requirements.json'));
  await idle();
  assert.equal(await page.locator('.tp-req-row').count(), 10);
  await page.locator('#tp-pdf-input').setInputFiles(['trade_license_2026.pdf','03_tin_certificate.pdf','04_vat_certificate.pdf','bank_solvency.pdf','experience_cert.pdf','experience_cert (1).pdf','02_technical_proposal.pdf','01_financial_proposal.pdf','scan_0042.pdf','trade_license_2025.pdf','company_logo.png'].map(n=>path.join(docs,n)));
  await idle();
  assert.equal(await page.locator('#tp-file-list > li').count(), 10);
  assert.ok((await page.locator('body').innerText()).includes('Duplicate content'));
  record('Actual JSON and ten PDFs loaded; PNG rejected; duplicate content flagged');
  await page.screenshot({ path: path.join(screenshots, '01-missing-and-duplicates.png'), fullPage: true });
  const mapping={R01:'trade_license_2026.pdf',R02:'03_tin_certificate.pdf',R03:'04_vat_certificate.pdf',R04:'bank_solvency.pdf',R05:'experience_cert.pdf',R08:'02_technical_proposal.pdf',R09:'01_financial_proposal.pdf',R10:'scan_0042.pdf'};
  for (const [id,name] of Object.entries(mapping)) await match(id,name);
  await page.locator('#tp-expiry-R01').fill('2027-06-30');
  await page.locator('#tp-expiry-R04').fill('2026-12-31');
  assert.equal(await page.locator('#tp-generate').isEnabled(), true);
  await match('R06','experience_cert (1).pdf');
  assert.equal(await page.locator('#tp-match-R06').inputValue(), '');
  record('All mandatory matches and expiry dates pass; duplicate assignment rejected');
  await page.locator('#tp-expiry-R01').fill('2026-10-19');
  assert.equal(await page.locator('#tp-generate').isDisabled(), true);
  assert.ok(await page.locator('.tp-req-row-expired').count());
  await page.screenshot({ path: path.join(screenshots, '02-expired-blocked.png'), fullPage: true });
  await page.locator('#tp-expiry-R01').fill('2026-10-20');
  assert.equal(await page.locator('#tp-generate').isEnabled(), true);
  assert.equal(await page.locator('#tp-expiry-R01').evaluate(el=>document.activeElement===el), true);
  await page.locator('#tp-expiry-R01').fill('2027-06-30');
  record('Expiry before deadline blocks; equal deadline passes; date focus retained');
  await page.locator('#tp-generate').click(); await idle();
  const link=page.locator('a[download$="_Package.pdf"]');
  await link.waitFor();
  const [download]=await Promise.all([page.waitForEvent('download'),link.click()]);
  assert.equal(download.suggestedFilename(),'T-2026-0417_Package.pdf');
  await download.saveAs(path.join(output, download.suggestedFilename()));
  await page.screenshot({ path: path.join(screenshots, '03-ready-and-download.png'), fullPage: true });
  record('Browser generated and downloaded the actual sample package');
  await page.locator('#tp-json-input').setInputFiles(path.join(docs,'company_logo.png')); await idle();
  assert.equal(await link.count(),1);
  assert.equal(await page.locator('#tp-file-list > li').count(),10);
  record('Invalid requirements replacement preserves working documents and download');
  await page.locator('.tp-lang-btn').click();
  assert.equal(await page.locator('html').getAttribute('lang'),'bn');
  const [csv]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'চেকলিস্ট রপ্তানি (CSV)',exact:true}).click()]);
  await csv.saveAs(path.join(output,csv.suggestedFilename()));
  const csvText=await readFile(path.join(output,csv.suggestedFilename()),'utf8');
  assert.ok(csvText.includes('নথি'));
  await page.setViewportSize({width:360,height:800});
  const sizes=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(sizes.scroll<=sizes.width,`Mobile overflow ${JSON.stringify(sizes)}`);
  await page.screenshot({path:path.join(screenshots,'04-bangla-mobile.png'),fullPage:true});
  record('Bangla UI and CSV download pass; 360px layout has no horizontal overflow');
  await page.locator('.tp-lang-btn').click();
  await page.setViewportSize({width:1440,height:1000});
  await match('R01','trade_license_2025.pdf');
  assert.equal(await page.locator('#tp-expiry-R01').inputValue(),'');
  assert.equal(await link.count(),0);
  await page.locator('#tp-expiry-R01').fill('2025-06-30');
  assert.equal(await page.locator('#tp-generate').isDisabled(),true);
  record('Match replacement clears expiry and invalidates old download; expired 2025 file blocks');
  await page.getByRole('button',{name:'Reset / new project',exact:true}).click();
  assert.equal(await page.locator('.tp-req-row').count(),0);
  assert.equal(await page.locator('#tp-file-list').count(),0);
  assert.equal(await link.count(),0);
  assert.equal(await page.locator('#tp-generate').isDisabled(),true);
  record('Reset removes requirements, documents, matches and result');
  await page.locator('#tp-json-input').setInputFiles(path.join(fixture, 'requirements.json')); await idle();
  await page.locator('#tp-pdf-input').setInputFiles(Array(31).fill(path.join(docs,'experience_cert.pdf'))); await idle();
  assert.equal(await page.locator('#tp-file-list > li').count(),30);
  assert.ok((await page.locator('body').innerText()).includes('Maximum 30 PDF files'));
  record('Real native upload of 31 organizer PDFs accepts only the allowed 30');
  await page.getByRole('button',{name:'Reset / new project',exact:true}).click();
  assert.deepEqual(errors,[]);
  assert.deepEqual(unexpectedRequests,[]);
  record('No browser errors, cross-origin requests or POST/PUT document uploads observed');
  await writeFile(path.join(output,'browser-acceptance.json'),JSON.stringify({url:page.url(),checkedAt:new Date().toISOString(),results,errors,unexpectedRequests},null,2)+'\n');
} finally { await browser.close(); }
